    Ticks = $false; FireDebug = $false; AllWeapons = $false; God = $false; Tune = $false; Extra = '' }

function Test-Setting($name, $value) {
    switch ($name) {
        Config { return $value -is [string] -and $value -in @('Release', 'Debug') }
        Backend { return $value -is [string] -and $value -in @('openxr', 'mock') }
        Class { return $value -is [int] -and $value -ge 1 -and $value -le 4 }
        Skill { return $value -is [int] -and $value -ge 0 -and $value -le 3 }
        Map { return $value -is [string] }
        Extra { return $value -is [string] }
        default { return $value -is [bool] }
    }
}
if (Test-Path -LiteralPath $settingsPath) {
    try {
        $saved = Get-Content -LiteralPath $settingsPath -Raw | ConvertFrom-Json
        foreach ($key in @($settings.Keys)) {
            $property = $saved.PSObject.Properties[$key]
            if ($null -ne $property -and (Test-Setting $key $property.Value)) { $settings[$key] = $property.Value }
        }
    } catch { Write-Warning "Cannot read launcher settings; using defaults: $_" }
}
foreach ($key in @('Config', 'Backend', 'Map', 'Class', 'Skill', 'Ticks', 'FireDebug', 'AllWeapons', 'God', 'Tune', 'Extra')) {
    if ($PSBoundParameters.ContainsKey($key)) {
        $value = $PSBoundParameters[$key]
        if ($value -is [System.Management.Automation.SwitchParameter]) { $value = [bool]$value }
        $settings[$key] = $value
    }
}

function Get-LaunchPlan($s) {
    $mapName = $s.Map.Trim()
    # Map is one engine token. Extra is the explicit unrestricted command field.
    if ($mapName -and $mapName -notmatch '^[A-Za-z0-9_/-]+$') { throw 'Map must contain only letters, numbers, underscores, hyphens or slashes.' }
    $exe = Join-Path $repoRoot "build\win64\$($s.Config)\hxn2vr.exe"
    $arguments = '-basedir . -window'
    if ($s.Backend -eq 'mock') { $arguments += ' -width 1280 -height 720' }
    $arguments += " -condebug +_enable_mouse 1 +vr_backend $($s.Backend)"
    if ($s.Backend -eq 'mock') { $arguments += ' +vr_mirror 2' }
    $arguments += ' +vr_enabled 1'
    $ticksValue = [int][bool]$s.Ticks
    $fireValue = [int][bool]$s.FireDebug
    $arguments += " +vr_debug_ticks $ticksValue +vr_debug_fire $fireValue +playerclass $($s.Class) +skill $($s.Skill)"
    $cfg = ''
    if ($mapName) {
        $arguments += " +map $mapName"
        $commands = @()
        if ($s.AllWeapons -and $s.Skill -lt 3) { $commands += 'impulse 9' }
        if ($s.God) { $commands += 'god' }
        if ($s.Tune) { $commands += 'vr_weapon_tune' }
        if ($commands.Count) {
            # 150 frames, as in smoke. Short lines and < 1 KB avoid Cbuf overflow.
            $lines = @('// Generated by launcher.ps1; commands require a loaded map.')
            for ($i = 0; $i -lt 15; $i++) { $lines += 'wait;wait;wait;wait;wait;wait;wait;wait;wait;wait' }
            $cfg = (($lines + $commands) -join "`n") + "`n"
            $arguments += ' +exec hxvr_launch.cfg'
        }
    }
    if ($s.Extra.Length) { $arguments += ' ' + $s.Extra }
    return [pscustomobject]@{ Exe = $exe; Arguments = $arguments; Cfg = $cfg }
}

if ($PrintCommand) {
    $plan = Get-LaunchPlan $settings
    Write-Output "Working directory: $gameDir"
    Write-Output "Exe: $($plan.Exe)"
    Write-Output "Arguments: $($plan.Arguments)"
    if ($plan.Cfg) { Write-Output "Cfg (hxvr_launch.cfg):`n$($plan.Cfg)" } else { Write-Output 'no cfg' }
    return
}

