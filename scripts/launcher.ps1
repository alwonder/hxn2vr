function Read-Controls {
    $settings.Config = 'Release'
    if ($debug.Checked) { $settings.Config = 'Debug' }
    $settings.Backend = 'openxr'
    if ($mock.Checked) { $settings.Backend = 'mock' }
    $settings.Build = $buildCheck.Checked
    $settings.Map = $mapBox.Text
    $settings.Class = $classBox.SelectedIndex + 1
    $settings.Skill = $skillBox.SelectedIndex
    $settings.Extra = $extraBox.Text
    foreach ($key in $checks.Keys) { $settings[$key] = $checks[$key].Checked }
}
function Update-Preview {
    Read-Controls
    $checks.AllWeapons.Enabled = $mapBox.Text.Trim().Length -gt 0 -and $settings.Skill -lt 3
    try {
        $plan = Get-LaunchPlan $settings
        $preview.Text = "Working directory: $gameDir`r`n`"$($plan.Exe)`" $($plan.Arguments)"
        $launch.Enabled = $true
    } catch { $preview.Text = $_.Exception.Message; $launch.Enabled = $false }
}
foreach ($control in @($release, $debug, $buildCheck, $openxr, $mock) + @($checks.Values)) {
    $control.Add_CheckedChanged({ Update-Preview })
}
foreach ($control in @($mapBox, $extraBox)) { $control.Add_TextChanged({ Update-Preview }) }
foreach ($control in @($classBox, $skillBox)) { $control.Add_SelectedIndexChanged({ Update-Preview }) }

function Assert-NoGame {
    if (Get-Process -Name hxn2vr -ErrorAction SilentlyContinue) { throw 'hxn2vr is already running. Close it before building or launching.' }
}
$openLog.Add_Click({
    try {
        $log = Join-Path $gameDir 'debug_h2.log'
        if (-not (Test-Path -LiteralPath $log -PathType Leaf)) { throw "Log not found: $log" }
        Start-Process -FilePath $log
    } catch { [void][System.Windows.Forms.MessageBox]::Show($_.Exception.Message, 'hxn2vr launcher') }
})
$script:busy = $false
$form.Add_FormClosing({ param($sender, $eventArgs) if ($script:busy) { $eventArgs.Cancel = $true } })
$launch.Add_Click({
    $process = $null
    try {
        Assert-NoGame
        Read-Controls
        $plan = Get-LaunchPlan $settings
        if (-not (Test-Path -LiteralPath (Join-Path $gameDir 'data1\pak0.pak') -PathType Leaf)) {
            throw 'Game data missing; run scripts/setup-gamedir.ps1 first.'
        }
        $script:busy = $true
        foreach ($control in $form.Controls) { $control.Enabled = $false }
        if ($settings.Build) {
            $status.Text = 'Building...'
            $info = New-Object System.Diagnostics.ProcessStartInfo
            $info.FileName = $cmake
            $info.Arguments = '--build --preset win64-' + $settings.Config.ToLowerInvariant()
            $info.WorkingDirectory = $repoRoot
            $info.UseShellExecute = $false
            $info.CreateNoWindow = $true
            $info.RedirectStandardOutput = $true
            $info.RedirectStandardError = $true
            $process = New-Object System.Diagnostics.Process
            $process.StartInfo = $info
            [void]$process.Start()
            # Drain both streams concurrently to avoid pipe deadlock; pump UI while waiting.
            $stdout = $process.StandardOutput.ReadToEndAsync()
            $stderr = $process.StandardError.ReadToEndAsync()
            while (-not $process.HasExited -or -not $stdout.IsCompleted -or -not $stderr.IsCompleted) {
                [System.Windows.Forms.Application]::DoEvents()
                [System.Threading.Thread]::Sleep(50)
            }
            $process.WaitForExit()
            if ($process.ExitCode -ne 0) {
                $lines = ($stdout.Result + "`n" + $stderr.Result) -split '\r?\n'
                $errors = @($lines | Where-Object { $_ -match '(?i)error|failed|fatal' } | Select-Object -Last 15)
                if (-not $errors.Count) { $errors = @($lines | Where-Object { $_.Trim() } | Select-Object -Last 15) }
                throw ("Build failed (exit $($process.ExitCode)):`r`n" + ($errors -join "`r`n"))
            }
        }
        Assert-NoGame
        if (-not (Test-Path -LiteralPath $plan.Exe -PathType Leaf)) { throw "Selected executable not found: $($plan.Exe)" }
        if ($plan.Cfg) { Set-Content -LiteralPath $cfgPath -Value $plan.Cfg -Encoding ASCII }
        elseif (Test-Path -LiteralPath $cfgPath) { Remove-Item -LiteralPath $cfgPath -Force }
        $settings | ConvertTo-Json | Set-Content -LiteralPath $settingsPath -Encoding UTF8
        Assert-NoGame
        Start-Process -FilePath $plan.Exe -ArgumentList $plan.Arguments -WorkingDirectory $gameDir
        $status.Text = 'Launched'
    } catch {
        $status.Text = 'Launch stopped'
        [void][System.Windows.Forms.MessageBox]::Show($_.Exception.Message, 'hxn2vr launcher')
    } finally {
        if ($null -ne $process) { $process.Dispose() }
        $script:busy = $false
        foreach ($control in $form.Controls) { $control.Enabled = $true }
        Update-Preview
    }
})
Update-Preview
[void]$form.ShowDialog()
$form.Dispose()
