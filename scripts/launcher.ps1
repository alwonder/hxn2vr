function Add-Control($type, $text, $x, $y, $width, $height, $parent = $form) {
    $control = New-Object "System.Windows.Forms.$type"
    $control.Text = $text
    $control.SetBounds($x, $y, $width, $height)
    $parent.Controls.Add($control)
    return $control
}
